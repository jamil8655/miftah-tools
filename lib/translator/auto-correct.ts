/**
 * Normalizes Urdu Unicode characters (e.g. converting Arabic letters to native Urdu Nastaliq letters)
 */
function normalizeUrduUnicode(text: string): string {
  return text
    // Arabic Kaf to Urdu Kaf (ك -> ک)
    .replace(/\u0643/g, '\u06A9')
    // Arabic Yeh with dots or Alif Maqsura to Urdu Yeh (ي, ى -> ی)
    .replace(/[\u064A\u0649]/g, '\u06CC')
    // Arabic He to Urdu Gol He (ه -> ہ)
    .replace(/\u0647/g, '\u06C1')
    // Normalizing double diacritics
    .replace(/[\u064B-\u065F\u0670]/g, '')
    // Zero-width joiner cleanups
    .replace(/[\u200B-\u200D\uFEFF]/g, '');
}

/**
 * Clean & smart auto-correct function for spoken text
 */
export function autoCorrectSpokenText(text: string, langCode: string): string {
  if (!text || !text.trim()) return '';

  let cleaned = text.trim();
  const normalizedLang = langCode.toLowerCase().split('-')[0];

  if (normalizedLang === 'ur') {
    // 1. Unicode character normalization for native Urdu
    cleaned = normalizeUrduUnicode(cleaned);

    // 2. Multi-word phrase corrections
    for (const [pattern, replacement] of URDU_PHRASE_CORRECTIONS) {
      cleaned = cleaned.replace(pattern, replacement);
    }

    // 3. Word-by-word vocabulary corrections
    cleaned = cleaned
      .split(/\s+/)
      .map((w) => URDU_WORD_CORRECTIONS[w] || w)
      .join(' ');
  } else if (normalizedLang === 'ar') {
    for (const [wrong, right] of Object.entries(ARABIC_CORRECTIONS)) {
      const regex = new RegExp(`(^|\\s)${wrong}(\\s|$)`, 'gi');
      cleaned = cleaned.replace(regex, `$1${right}$2`);
    }

    cleaned = cleaned
      .split(/\s+/)
      .map((w) => ARABIC_CORRECTIONS[w] || w)
      .join(' ');
  } else if (normalizedLang === 'hi') {
    for (const [wrong, right] of Object.entries(HINDI_CORRECTIONS)) {
      const regex = new RegExp(`(^|\\s)${wrong}(\\s|$)`, 'gi');
      cleaned = cleaned.replace(regex, `$1${right}$2`);
    }

    cleaned = cleaned
      .split(/\s+/)
      .map((w) => HINDI_CORRECTIONS[w] || w)
      .join(' ');
  } else if (normalizedLang === 'en') {
    for (const [wrong, right] of Object.entries(ENGLISH_CORRECTIONS)) {
      const regex = new RegExp(`\\b${wrong}\\b`, 'gi');
      cleaned = cleaned.replace(regex, right);
    }
  }

  // Remove multiple adjacent spaces
  cleaned = cleaned.replace(/\s{2,}/g, ' ').trim();

  return cleaned;
}
